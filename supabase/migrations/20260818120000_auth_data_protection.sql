alter table public.sessions force row level security;
alter table public.students force row level security;
alter table public.bins force row level security;
alter table public.queue_entries force row level security;
alter table public.reservations force row level security;
alter table public.rentals force row level security;
alter table public.notification_outbox force row level security;
alter table public.audit_events force row level security;
alter table public.inbound_sms_events force row level security;
alter table public.staff_web_sessions enable row level security;
alter table public.staff_web_sessions force row level security;
alter table public.rate_limit_buckets enable row level security;
alter table public.rate_limit_buckets force row level security;

do $$
declare
  v_table text;
  v_role text;
begin
  foreach v_table in array array[
    'sessions',
    'students',
    'bins',
    'queue_entries',
    'reservations',
    'rentals',
    'notification_outbox',
    'audit_events',
    'inbound_sms_events',
    'staff_web_sessions',
    'rate_limit_buckets'
  ] loop
    execute format(
      'create policy %I on public.%I as restrictive for all to public using (false) with check (false)',
      v_table || '_browser_deny',
      v_table
    );
    execute format('revoke all on table public.%I from public', v_table);
    foreach v_role in array array['anon', 'authenticated'] loop
      if exists (select 1 from pg_roles where rolname = v_role) then
        execute format('revoke all on table public.%I from %I', v_table, v_role);
      end if;
    end loop;
  end loop;

  foreach v_table in array array[
    'v_current_out_rentals',
    'v_current_late_rentals',
    'v_all_late_rentals',
    'v_inventory',
    'v_session_rentals',
    'v_current_waitlist'
  ] loop
    execute format('revoke all on table public.%I from public', v_table);
    foreach v_role in array array['anon', 'authenticated'] loop
      if exists (select 1 from pg_roles where rolname = v_role) then
        execute format('revoke all on table public.%I from %I', v_table, v_role);
      end if;
    end loop;
  end loop;

  execute 'revoke all on all sequences in schema public from public';
  execute 'alter default privileges for role postgres in schema public revoke all on tables from public';
  execute 'alter default privileges for role postgres in schema public revoke all on sequences from public';
  -- PostgreSQL's built-in PUBLIC execute grant is global. A per-schema REVOKE
  -- cannot override it, so remove it from the owner's global defaults.
  execute 'alter default privileges for role postgres revoke execute on functions from public';
  execute 'alter default privileges in schema public revoke all on tables from public';
  execute 'alter default privileges in schema public revoke all on sequences from public';
  execute 'alter default privileges revoke execute on functions from public';

  foreach v_role in array array['anon', 'authenticated'] loop
    if exists (select 1 from pg_roles where rolname = v_role) then
      execute format(
        'revoke all on all sequences in schema public from %I',
        v_role
      );
      execute format(
        'alter default privileges for role postgres in schema public revoke all on tables from %I',
        v_role
      );
      execute format(
        'alter default privileges for role postgres in schema public revoke all on sequences from %I',
        v_role
      );
      execute format(
        'alter default privileges for role postgres in schema public revoke execute on functions from %I',
        v_role
      );
      execute format(
        'alter default privileges in schema public revoke all on tables from %I',
        v_role
      );
      execute format(
        'alter default privileges in schema public revoke all on sequences from %I',
        v_role
      );
      execute format(
        'alter default privileges in schema public revoke execute on functions from %I',
        v_role
      );
    end if;
  end loop;

  if exists (select 1 from pg_roles where rolname = 'service_role') then
    execute 'grant select, insert, update, delete on public.staff_web_sessions to service_role';
    execute 'grant select, insert, update, delete on public.rate_limit_buckets to service_role';
  end if;
end;
$$;

-- The application does not consume Postgres Changes. Remove protected tables
-- from Supabase Realtime even if a previous environment added them manually;
-- this keeps PII and credential metadata out of the replication channel.
do $$
declare
  v_table text;
begin
  if exists (
    select 1 from pg_publication where pubname = 'supabase_realtime'
  ) then
    foreach v_table in array array[
      'sessions',
      'students',
      'bins',
      'queue_entries',
      'reservations',
      'rentals',
      'notification_outbox',
      'audit_events',
      'inbound_sms_events',
      'staff_web_sessions',
      'rate_limit_buckets'
    ] loop
      if exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = v_table
      ) then
        execute format(
          'alter publication supabase_realtime drop table public.%I',
          v_table
        );
      end if;
    end loop;
  end if;
end;
$$;

